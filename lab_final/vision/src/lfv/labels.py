"""Label store shared by autolabel.py (writes auto.json) and review.py (writes labels.json).

auto.json   {image_id: AutoResult}  -- model output, regenerated by autolabel.py
labels.json {image_id: Label}       -- the human-reviewed truth; never written by autolabel

image_id = '<folder>/<file>' relative to the raw image root (../lab_6/data/raw).
Boxes are [x0, y0, x1, y1, cls] in source pixels; cls uses the lab_6 ids 1..5
(1 left, 2 right, 3 do_not_enter, 4 stop, 5 goal). An empty list = no sign.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT.parent / 'lab_6' / 'data' / 'raw'
LABEL_DIR = ROOT / 'data' / 'labels'
AUTO = LABEL_DIR / 'auto.json'
LABELS = LABEL_DIR / 'labels.json'

CLASS_NAMES = {0: 'empty', 1: 'left', 2: 'right', 3: 'do_not_enter', 4: 'stop', 5: 'goal'}

# Review flags (autolabel.py) and how much each moves an image up the review queue.
FLAG_WEIGHT = {
    'no_box': 5,          # a model found nothing on a sign image
    'disagree': 4,        # the two models' top boxes overlap little
    'huge_box': 4,        # box covers most of the image (whole-wall failure)
    'low_score': 2,       # weak top score
    'sign_on_empty': 2,   # confident box on an image labeled empty wall
    'edge': 1,            # box touches the image border (sign may be cut off)
}


def image_ids(raw: Path = RAW) -> list[tuple[str, int]]:
    """(image_id, lab_6 class) for every labeled image under raw/."""
    out = []
    for d in sorted(p for p in raw.iterdir() if (p / 'labels.txt').exists()):
        for line in (d / 'labels.txt').read_text().splitlines():
            if line.strip():
                k, v = (s.strip() for s in line.split(','))
                ext = next((e for e in ('.png', '.jpg') if (d / f'{k}{e}').exists()), None)
                if ext:
                    out.append((f'{d.name}/{k}{ext}', int(v)))
    return out


def load(path: Path) -> dict:
    return json.loads(path.read_text()) if path.exists() else {}


def save(path: Path, data: dict) -> None:
    """Atomic write (a crash mid-save must not lose reviewed labels)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix('.tmp')
    tmp.write_text(json.dumps(data, indent=1, sort_keys=True))
    os.replace(tmp, path)
